#!/usr/bin/env node
/**
 * Prints a range of migrations as one script, in order, for pasting into the
 * Supabase SQL editor.
 *
 * The editor takes one paste at a time, and applying nine files by hand invites
 * skipping one — which is how a guard ends up live on one table and missing on
 * the next. Every migration is written to survive being run twice, so a bundle
 * that includes something already applied is safe.
 *
 *   node scripts/bundle-migrations.mjs 050 059 > /tmp/apply.sql
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "supabase", "migrations");

const [from = "000", to = "999"] = process.argv.slice(2);
const numberOf = (file) => file.slice(0, 3);

const files = fs
  .readdirSync(dir)
  .filter((file) => file.endsWith(".sql"))
  .filter((file) => numberOf(file) >= from && numberOf(file) <= to)
  .sort();

if (files.length === 0) {
  console.error(`No migrations between ${from} and ${to}.`);
  process.exit(1);
}

const parts = [
  `-- Migrations ${numberOf(files[0])}–${numberOf(files[files.length - 1])}, in order.`,
  `-- Generated by scripts/bundle-migrations.mjs. Safe to run more than once.`,
  "",
];

for (const file of files) {
  parts.push(
    "-- ============================================================",
    `-- ${file}`,
    "-- ============================================================",
    "",
    fs.readFileSync(path.join(dir, file), "utf8").trimEnd(),
    "",
  );
}

process.stdout.write(`${parts.join("\n")}\n`);
